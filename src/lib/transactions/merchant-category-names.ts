/** The short name for a merchant category code, or null when unknown. */
export function merchantCategoryName(code: string | null | undefined): string | null {
  if (!code) return null;
  const named = MERCHANT_CATEGORY_NAMES[code];
  if (named) return named;
  // Codes 3000-3999 name a single airline, car rental firm or hotel chain;
  // the ranges are enough to say which kind.
  if (/^3\d{3}$/.test(code)) {
    const n = Number(code);
    if (n <= 3350) return "Airlines";
    if (n <= 3500) return "Car rental";
    return "Hotels and lodging";
  }
  return null;
}

/** "5812 · Restaurants", or just "5812" for a code with no known name. */
export function formatMerchantCategory(code: string | null | undefined): string | null {
  if (!code) return null;
  const name = merchantCategoryName(code);
  return name ? `${code} · ${name}` : code;
}
